#!/usr/bin/env bun

import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { OFFICIAL_PLUGIN_MANIFEST } from '../packages/plugins/src/manifest/index.ts';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const PACKAGE_PATH = fileURLToPath(new URL('../packages/plugins/package.json', import.meta.url));
const EXPORTS_PATH = fileURLToPath(
  new URL('../packages/plugins/src/generated-plugin-exports.ts', import.meta.url),
);
const FACTORIES_PATH = fileURLToPath(
  new URL('../packages/plugins/src/factories/index.ts', import.meta.url),
);
const AUDIT_PATH = fileURLToPath(
  new URL('../packages/plugins/src/audit/index.ts', import.meta.url),
);
const DOC_PATH = fileURLToPath(new URL('../packages/plugins/PLUGIN_CATALOG.md', import.meta.url));
const write = process.argv.includes('--write');
const WEBSITE_CATALOG_PATH = fileURLToPath(
  new URL('../website/src/data/runtime-catalog.ts', import.meta.url),
);
const WEBSITE_DETAILS_PATH = fileURLToPath(
  new URL('../website/src/data/plugin-details-workflows.ts', import.meta.url),
);

async function websiteProjections() {
  const { HOST_PLUGIN_AUDIT_ENTRIES } = await import(
    '../packages/plugins/dist/plugin-audit-catalog.js'
  );
  const host = HOST_PLUGIN_AUDIT_ENTRIES.map(({ canDisable: _, ...entry }) => ({
    ...entry,
    name: entry.name === 'lsp' ? '@wrongstack/plug-lsp' : entry.name,
    source: ['lsp', 'telegram'].includes(entry.name) ? 'Bridge' : 'Core',
  }));
  const official = [];
  const details = {};
  for (const entry of OFFICIAL_PLUGIN_MANIFEST) {
    const plugin = await loadPlugin(entry);
    official.push({
      name: entry.name,
      risk: entry.audit.risk,
      summary: plugin.description,
      defaultState: entry.audit.defaultState,
      source: 'Suite',
    });
    const source = readFileSync(`${ROOT}/packages/plugins/src/${entry.name}/index.ts`, 'utf8');
    if (!source.includes('workflowPlugin(') && !source.includes('createEvidenceAnalyzerPlugin('))
      continue;
    // These on-demand factories register metadata only at setup, never spawn or fetch.
    const tools = [];
    const api = {
      tools: {
        register(tool) {
          tools.push(tool);
        },
      },
      config: { extensions: {} },
      log: { info() {} },
    };
    await plugin.setup(api);
    try {
      details[entry.name] = {
        version: plugin.version,
        apiVersion: plugin.apiVersion,
        longDescription: `${plugin.description}. Opt in through config.plugins; tools run only when invoked. ${tools.map((tool) => tool.description).join(' ')}`,
        tools: tools.map((tool) => ({
          name: tool.name,
          category: tool.category,
          permission: tool.permission,
          mutating: tool.mutating,
          summary: tool.description,
          params: Object.entries(tool.inputSchema.properties ?? {}).map(([name, schema]) => ({
            name,
            type: schema.type ?? 'any',
            description:
              schema.description ??
              ((tool.inputSchema.required ?? []).includes(name) ? 'Required.' : 'Optional.'),
          })),
        })),
        configOptions: Object.entries(plugin.configSchema.properties ?? {}).map(
          ([name, schema]) => ({
            name,
            type: schema.type,
            defaultValue: String(schema.default ?? ''),
            description: schema.description ?? '',
          }),
        ),
        hooks: [],
        example: JSON.stringify({ plugins: [{ name: entry.name, enabled: true }] }, null, 2),
      };
    } finally {
      await plugin.teardown?.(api);
    }
  }
  const catalog = readFileSync(WEBSITE_CATALOG_PATH, 'utf8').replace(
    /export const pluginCatalog = \[[\s\S]*?\] as const;/,
    `export const pluginCatalog = ${JSON.stringify([...host, ...official], null, 2)} as const;`,
  );
  return [
    { path: WEBSITE_CATALOG_PATH, content: formatTypeScript(WEBSITE_CATALOG_PATH, catalog) },
    {
      path: WEBSITE_DETAILS_PATH,
      content: formatTypeScript(
        WEBSITE_DETAILS_PATH,
        `// Generated by scripts/generate-plugin-projections.mjs. Do not edit.\nimport type { PluginDetail } from './plugin-detail-types';\nexport const workflowPluginDetails: Record<string, PluginDetail> = ${JSON.stringify(details, null, 2)};\n`,
      ),
    },
  ];
}

function assertManifest() {
  const names = new Set();
  const exports = new Set();
  for (const entry of OFFICIAL_PLUGIN_MANIFEST) {
    if (!/^[a-z0-9-]+$/.test(entry.name)) throw new Error(`Invalid plugin name: ${entry.name}`);
    if (names.has(entry.name)) throw new Error(`Duplicate plugin name: ${entry.name}`);
    if (exports.has(entry.exportName))
      throw new Error(`Duplicate plugin export: ${entry.exportName}`);
    names.add(entry.name);
    exports.add(entry.exportName);
  }
}

function renderExports() {
  return [
    '// Generated by scripts/generate-plugin-projections.mjs. Do not edit.',
    ...[...OFFICIAL_PLUGIN_MANIFEST]
      .sort((a, b) => a.name.localeCompare(b.name))
      .map((entry) => `export { default as ${entry.exportName} } from './${entry.name}/index.js';`),
    '',
  ].join('\n');
}

function formatTypeScript(path, content) {
  const result = spawnSync(
    process.execPath,
    ['run', 'biome', 'format', '--stdin-file-path', path],
    {
      cwd: ROOT,
      encoding: 'utf8',
      input: content,
    },
  );
  if (result.status !== 0) {
    throw new Error(`Failed to format generated ${path}: ${result.stderr || result.stdout}`);
  }
  return result.stdout;
}

function renderFactories() {
  return [
    '// Generated by scripts/generate-plugin-projections.mjs. Do not edit.',
    "import type { Plugin } from '@wrongstack/core/types';",
    '',
    'export const OFFICIAL_PLUGIN_SPECIFIERS = [',
    ...OFFICIAL_PLUGIN_MANIFEST.map((entry) => `  '${entry.importSpecifier}',`),
    '] as const;',
    '',
    // One literal import() per plugin, never `import(specifier)`: bundlers
    // (the standalone `bun build --compile` binary) only follow literal
    // specifiers, and a computed one silently drops every official plugin.
    'const loadDefault = async (module: Promise<{ default: Plugin }>): Promise<Plugin> =>',
    '  (await module).default;',
    '',
    'export const OFFICIAL_PLUGIN_FACTORIES: readonly (() => Promise<Plugin>)[] = [',
    ...OFFICIAL_PLUGIN_MANIFEST.map(
      (entry) => `  () => loadDefault(import('${entry.importSpecifier}')),`,
    ),
    '];',
    '',
  ].join('\n');
}

function expectedPackageExports(pkg) {
  const result = {
    '.': pkg.exports['.'],
    './manifest': {
      types: './dist/manifest.d.ts',
      import: './dist/manifest.js',
    },
    './factories': {
      types: './dist/factories.d.ts',
      import: './dist/factories.js',
    },
    './audit': {
      types: './dist/audit.d.ts',
      import: './dist/audit.js',
    },
    './plugin-audit-catalog': {
      types: './dist/plugin-audit-catalog.d.ts',
      import: './dist/plugin-audit-catalog.js',
    },
  };
  for (const entry of OFFICIAL_PLUGIN_MANIFEST) {
    result[entry.packageSubpath] = {
      types: `./dist/${entry.name}.d.ts`,
      import: `./dist/${entry.name}.js`,
    };
  }
  result['./runtime'] = {
    types: './dist/runtime.d.ts',
    import: './dist/runtime.js',
  };
  return result;
}

async function loadPlugin(entry) {
  const modulePath = pathToFileURL(`${ROOT}/packages/plugins/dist/${entry.name}.js`).href;
  const plugin = (await import(modulePath)).default;
  if (plugin?.name !== entry.name) {
    throw new Error(
      `Plugin manifest name ${entry.name} does not match implementation name ${String(plugin?.name)}`,
    );
  }
  return plugin;
}

async function renderDocs() {
  const lines = [
    '# Official Plugin Catalog',
    '',
    '<!-- Generated by scripts/generate-plugin-projections.mjs. Do not edit. -->',
    '',
    '| Plugin | Version | API | Import | Description |',
    '|---|---|---|---|---|',
  ];
  for (const entry of OFFICIAL_PLUGIN_MANIFEST) {
    const plugin = await loadPlugin(entry);
    const description = String(plugin.description ?? '')
      .replaceAll('|', '\\|')
      .replaceAll('\n', ' ');
    lines.push(
      `| ${entry.name} | ${plugin.version ?? '—'} | ${plugin.apiVersion ?? '—'} | \`${entry.importSpecifier}\` | ${description} |`,
    );
  }
  lines.push('');
  return lines.join('\n');
}

async function renderAuditEntries() {
  const lines = [
    '// Generated by scripts/generate-plugin-projections.mjs. Do not edit.',
    'export const OFFICIAL_PLUGIN_AUDIT_ENTRIES = [',
  ];
  for (const entry of OFFICIAL_PLUGIN_MANIFEST) {
    const plugin = await loadPlugin(entry);
    lines.push('  {');
    lines.push(`    name: ${JSON.stringify(entry.name)},`);
    lines.push(`    risk: ${JSON.stringify(entry.audit.risk)},`);
    lines.push(`    summary: ${JSON.stringify(plugin.description ?? '')},`);
    lines.push(`    defaultState: ${JSON.stringify(entry.audit.defaultState)},`);
    lines.push('    canDisable: true,');
    lines.push('  },');
  }
  lines.push('] as const;', '');
  return lines.join('\n');
}

assertManifest();
const pkg = JSON.parse(readFileSync(PACKAGE_PATH, 'utf8'));
const packageExports = expectedPackageExports(pkg);
// Identity projections must exist BEFORE building newly added entry points.
// Metadata projections still require a successful build of implementations.
if (process.argv.includes('--bootstrap')) {
  writeFileSync(EXPORTS_PATH, formatTypeScript(EXPORTS_PATH, renderExports()), 'utf8');
  writeFileSync(FACTORIES_PATH, formatTypeScript(FACTORIES_PATH, renderFactories()), 'utf8');
  pkg.exports = packageExports;
  writeFileSync(PACKAGE_PATH, `${JSON.stringify(pkg, null, 2)}\n`, 'utf8');
  process.stdout.write('Bootstrapped plugin identities for build.\n');
  process.exit(0);
}
const outputs = [
  { path: EXPORTS_PATH, content: formatTypeScript(EXPORTS_PATH, renderExports()) },
  { path: FACTORIES_PATH, content: formatTypeScript(FACTORIES_PATH, renderFactories()) },
  { path: AUDIT_PATH, content: formatTypeScript(AUDIT_PATH, await renderAuditEntries()) },
  { path: DOC_PATH, content: await renderDocs() },
  ...(await websiteProjections()),
];

if (write) {
  for (const output of outputs) {
    writeFileSync(output.path, output.content, 'utf8');
    process.stdout.write(`Updated ${output.path}\n`);
  }
  pkg.exports = packageExports;
  writeFileSync(PACKAGE_PATH, `${JSON.stringify(pkg, null, 2)}\n`, 'utf8');
  process.stdout.write(`Updated ${PACKAGE_PATH}\n`);
  process.exit(0);
}

for (const output of outputs) {
  if (readFileSync(output.path, 'utf8') !== output.content) {
    throw new Error(
      `Plugin projection drift detected in ${output.path}. Run \`pnpm plugins:manifest:write\`.`,
    );
  }
}
if (JSON.stringify(pkg.exports) !== JSON.stringify(packageExports)) {
  throw new Error(
    `Plugin package exports drift detected in ${PACKAGE_PATH}. Run \`pnpm plugins:manifest:write\`.`,
  );
}
process.stdout.write('Plugin projections match the typed manifest.\n');
