#!/usr/bin/env bun

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  PROVIDER_DEFINITIONS,
  projectPopularProviderCatalog,
} from '../packages/providers/dist/provider-definitions.js';

const CATALOG_PATH = fileURLToPath(
  new URL('../packages/webui/public/providers.json', import.meta.url),
);
const DOC_PATH = fileURLToPath(
  new URL('../packages/providers/PROVIDER_CATALOG.md', import.meta.url),
);

function markdownCell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function renderProviderDocs() {
  const lines = [
    '# Provider Catalog',
    '',
    '<!-- Generated by scripts/generate-provider-catalog.mjs. Do not edit by hand. -->',
    '',
    '| ID | Name | Family | Usage | Default endpoint | Environment variables | Models |',
    '|---|---|---|---|---|---|---|',
  ];
  for (const definition of Object.values(PROVIDER_DEFINITIONS)) {
    lines.push(
      `| ${[
        definition.id,
        definition.name,
        definition.family,
        definition.usage,
        definition.baseUrl ?? '—',
        definition.envVars.join(', ') || '—',
        definition.models.join(', ') || 'catalog/discovery',
      ]
        .map(markdownCell)
        .join(' | ')} |`,
    );
  }
  lines.push('');
  return lines.join('\n');
}

const outputs = [
  {
    path: CATALOG_PATH,
    content: `${JSON.stringify(projectPopularProviderCatalog(), null, 2)}\n`,
  },
  { path: DOC_PATH, content: renderProviderDocs() },
];
const write = process.argv.includes('--write');

if (write) {
  for (const output of outputs) {
    writeFileSync(output.path, output.content, 'utf8');
    process.stdout.write(`Updated ${output.path}\n`);
  }
  process.exit(0);
}

for (const output of outputs) {
  const actual = readFileSync(output.path, 'utf8');
  if (actual !== output.content) {
    process.stderr.write(
      `Provider projection drift detected in ${output.path}. Run \`pnpm providers:catalog:write\` and commit the generated snapshots.\n`,
    );
    process.exit(1);
  }
}

process.stdout.write('Provider catalog snapshots match the canonical registry.\n');
