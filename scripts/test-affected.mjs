#!/usr/bin/env node
/**
 * Run only the test files that something under them changed.
 *
 * The problem this solves: a full root run is ~15 minutes and 39,827 tests,
 * and while iterating on one package almost all of it re-proves what it proved
 * an hour ago. A test can only start failing if code it reaches changed, so
 * re-running one whose entire import closure is byte-identical — and which
 * passed last time — buys nothing.
 *
 * How this decides. The cache is a list of files known to have PASSED together
 * with everything they imported; a file is dropped from the skip list, i.e. it
 * RUNS, when any of these holds:
 *   - it has no cache entry (new, or its import graph was never observed)
 *   - the salt changed (a vitest config, setup file, lockfile or the root
 *     manifest moved, which can change any test's behaviour)
 *   - it did not pass last time
 *   - any file in its recorded import closure has a different hash, or is gone
 *
 * Note the direction: this script never decides what to RUN, only what is
 * provably safe to SKIP. Vitest still enumerates the suite through its own
 * `include` globs, so a test file this script has never heard of runs by
 * default. That asymmetry is deliberate — a second copy of the include globs
 * here could drift, and a drifted include list means silently never running a
 * test file, which this repo already hit once when a `*.test.ts`-only glob
 * skipped every `.tsx` suite and they "passed" CI by never running.
 *
 * The one blind spot: a test that reads a fixture at RUNTIME without importing
 * it has no graph edge to that fixture, so editing the fixture alone will not
 * mark the test dirty. That is why this is a local iteration aid and not a
 * gate — CI and `pnpm release:check` always run everything. `--all` forces a
 * full run and re-seeds the cache.
 *
 * Usage:
 *   pnpm test:affected                  # run what changed
 *   pnpm test:affected --all            # run everything, refresh the cache
 *   pnpm test:affected --list           # print the plan, run nothing
 *   pnpm test:affected -- -t "pattern"  # extra args go through to vitest
 */
import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import { rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { hashFile, REPO_ROOT, readCache } from './lib/affected-cache.mjs';

/**
 * Files that can change what ANY test does. A change here invalidates the whole
 * cache rather than any particular entry, because none of them appear in a test
 * file's import graph while all of them shape the run.
 */
const SALT_FILES = [
  'vitest.config.ts',
  'vitest.workers.ts',
  'vitest.setup.ts',
  'vitest.globalTeardown.ts',
  'scripts/vitest-core-aliases.mjs',
  'package.json',
  'pnpm-lock.yaml',
];

/**
 * The generated config lives at the repo root on purpose. Vite derives its
 * `root` from the config file's directory, and anywhere else would shift alias
 * and glob resolution out from under the base config.
 */
const GENERATED_CONFIG = path.join(REPO_ROOT, 'vitest.affected.generated.config.ts');

function parseArgs(argv) {
  const options = { all: false, list: false, passthrough: [] };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--') {
      options.passthrough.push(...argv.slice(i + 1));
      break;
    }
    if (arg === '--all') options.all = true;
    else if (arg === '--list') options.list = true;
    else options.passthrough.push(arg);
  }
  return options;
}

function computeSalt() {
  const hash = createHash('sha256');
  for (const file of SALT_FILES) hash.update(`${file}:${hashFile(file) ?? 'missing'}\n`);
  return hash.digest('hex').slice(0, 16);
}

/** Why this cached file has to run again, or null when it is safe to skip. */
function dirtyReason(entry, cache, hashCache) {
  if (entry.status !== 'pass') return 'did not pass last time';
  for (const dep of entry.deps) {
    let current = hashCache.get(dep);
    if (current === undefined) {
      current = hashFile(dep);
      hashCache.set(dep, current);
    }
    if (current === null) return `dependency vanished: ${dep}`;
    if (current !== cache.hashes[dep]) return `changed: ${dep}`;
  }
  return null;
}

/**
 * A config that is the real one plus the skip list. Spreading the base keeps
 * every alias, pool and timeout setting authoritative in `vitest.config.ts`;
 * only `exclude` is extended.
 */
function writeGeneratedConfig(skip) {
  writeFileSync(
    GENERATED_CONFIG,
    [
      '// GENERATED by scripts/test-affected.mjs — do not edit, do not commit.',
      '// Deleted automatically when the run finishes.',
      "import base from './vitest.config.ts';",
      '',
      'const SKIP = ' + JSON.stringify(skip, null, 2) + ';',
      '',
      'export default {',
      '  ...base,',
      '  test: {',
      '    ...base.test,',
      '    exclude: [...(base.test?.exclude ?? []), ...SKIP],',
      '  },',
      '};',
      '',
    ].join('\n'),
    'utf8',
  );
}

const options = parseArgs(process.argv.slice(2));
const salt = computeSalt();
const cache = readCache();
const cachedFiles = Object.keys(cache.entries);

let fullRunReason = null;
let affectedCount = 0;
const skip = [];
if (options.all) {
  fullRunReason = '--all';
} else if (cachedFiles.length === 0) {
  fullRunReason = 'no cache yet — this run seeds it';
} else if (cache.salt !== salt) {
  fullRunReason = 'vitest config / lockfile changed';
} else {
  const hashCache = new Map();
  const reasons = new Map();
  for (const file of cachedFiles) {
    const why = dirtyReason(cache.entries[file], cache, hashCache);
    if (why) reasons.set(file, why);
    else skip.push(file);
  }
  affectedCount = reasons.size;
  for (const [file, why] of [...reasons].slice(0, 10)) console.log(`  run  ${file} — ${why}`);
  if (reasons.size > 10) console.log(`  … and ${reasons.size - 10} more`);
  console.log(
    `test:affected: ${reasons.size} known file(s) affected · ${skip.length} unchanged and green, skipped` +
      ' · anything not in the cache runs too',
  );
}

if (fullRunReason) console.log(`test:affected: running the full suite (${fullRunReason})`);
if (options.list) process.exit(0);

// Nothing to prove. Handing Vitest a skip list that covers every file it can
// see makes it exit with "No test files found", which reads like a broken
// setup rather than the good news it is.
if (!fullRunReason && affectedCount === 0) {
  console.log('test:affected: nothing to run — every cached file is unchanged and green.');
  process.exit(0);
}

const configArgs = [];
if (skip.length > 0) {
  writeGeneratedConfig(skip);
  configArgs.push(`--config=${path.basename(GENERATED_CONFIG)}`);
}

const recorder = path.join(REPO_ROOT, 'scripts', 'vitest-affected-recorder.mjs');
const args = [
  'vitest',
  'run',
  ...configArgs,
  '--reporter=default',
  `--reporter=${recorder}`,
  ...options.passthrough,
];
// String form via a shell resolves the `vitest` bin the same way a package.json
// script line would, on both Windows and POSIX.
const command = `npx ${args.map((a) => (/\s/.test(a) ? `"${a}"` : a)).join(' ')}`;
const child = spawn(command, {
  stdio: 'inherit',
  shell: true,
  cwd: REPO_ROOT,
  env: { ...process.env, WRONGSTACK_AFFECTED_SALT: salt },
});

function cleanup() {
  if (skip.length > 0) rmSync(GENERATED_CONFIG, { force: true });
}
// The generated config must not survive the run under any exit path; a stale
// one left at the repo root would silently skip tests on the next plain
// `vitest` invocation someone points at it.
process.on('exit', cleanup);
for (const signal of ['SIGINT', 'SIGTERM']) {
  process.on(signal, () => {
    try {
      child.kill(signal);
    } catch {
      // Already gone.
    }
    cleanup();
    process.exit(1);
  });
}
child.on('exit', (code) => {
  cleanup();
  process.exit(code ?? 1);
});
